#!/usr/bin/env python3
"""Build the Chapter 2 validation tables from validation_results.csv.

Writes, under $PLBOOST_OUT/tabelas/ (default: ./tabelas/):
    val_pl.tex          -> Table 2.3, PL validation (two scenarios)
    val_ipl_merged.tex  -> Table 2.4, IPL validation, the four submodels in one
                           grid, with the True column inside each scenario
                           because the true values of eta_alpha are what
                           defines the three scenarios.

Usage:
    python3 make_tables.py [CSV] [DECIMALS]

The csv is written by validation_multirep.R (default: $PLBOOST_OUT/validation_results.csv).
"""
import csv, sys

import os
OUT = os.environ.get("PLBOOST_OUT", ".")
CSV = sys.argv[1] if len(sys.argv) > 1 else os.path.join(OUT, "validation_results.csv")
os.makedirs(os.path.join(OUT, "tabelas"), exist_ok=True)
ND = int(sys.argv[2]) if len(sys.argv) > 2 else 4

MU  = [("mu.(Intercept)", "Intercept"), ("mu.V1", "$x_1$"), ("mu.V2", "$x_2$"),
       ("mu.V3", "$x_3$"), ("mu.V4", "$x_4$")]
SIG = [("sig.(Intercept)", "Intercept"), ("sig.V3", "$x_3$"),
       ("sig.V4", "$x_4$"), ("sig.V5", "$x_5$")]
LAM = [("lambda", "")]
AL  = [("al.(Intercept)", "Intercept"), ("al.U1", "$u_1$"), ("al.U2", "$u_2$")]

d = {}
for r in csv.DictReader(open(CSV)):
    d[(r["scenario"], r["coefficient"])] = r

def num(x):
    return f"{float(x):.{ND}f}"

def cells(sc, chave, com_true=True):
    r = d[(sc, chave)]
    out = [f"${num(r['true'])}$"] if com_true else []
    out.append(rf"${num(r['boost_mean'])}\,({num(r['boost_sd'])})$")
    out.append(rf"${num(r['mle_mean'])}\,({num(r['mle_sd'])})$")
    return out

def bloco(L, sub, linhas, cens, sep=False):
    L.append(r"\midrule")
    for i, (chave, rot) in enumerate(linhas):
        cs = []
        for j, sc in enumerate(cens):
            if sep and j > 0:
                cs.append("")
            cs += cells(sc, chave)
        L.append(f" {sub if i == 0 else ''} & {rot} & " + " & ".join(cs) + r" \\")

cab = ["% GENERATED by reproduce/ch2_validation/make_tables.py from",
       f"% validation_results.csv ({ND} decimals). Do not edit by hand."]

# ---- Table 2.3, PL -------------------------------------------------------
cens = ["PL Scenario 1", "PL Scenario 2"]
L = list(cab)
L += [r"{\footnotesize", r"\begin{tabular}{llrrrcrrr}", r"\toprule",
      r"& & \multicolumn{3}{c}{Scenario 1} & & \multicolumn{3}{c}{Scenario 2} \\",
      r"\cmidrule(lr){3-5}\cmidrule(lr){7-9}",
      r"Submodel & Coefficient & True & Boosting & MLE & & True & Boosting & MLE \\"]
bloco(L, r"$\eta_\mu$", MU, cens, sep=True)
bloco(L, r"$\eta_\sigma$", SIG, cens, sep=True)
bloco(L, r"$\log\lambda$", LAM, cens, sep=True)
L += [r"\bottomrule", r"\end{tabular}", "}"]
open(os.path.join(OUT, "tabelas", "val_pl.tex"), "w").write("\n".join(L) + "\n")

# ---- Table 2.4, IPL merged --------------------------------------------
cens = ["IPL High inflation", "IPL Medium inflation", "IPL Low inflation"]
L = list(cab)
L += [r"{\footnotesize", r"\begin{tabular}{llrrrrrrrrr}", r"\toprule",
      r"& & \multicolumn{3}{c}{High} & \multicolumn{3}{c}{Medium} & "
      r"\multicolumn{3}{c}{Low} \\",
      r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}\cmidrule(lr){9-11}",
      r"Submodel & Coefficient & True & Boost. & MLE & True & Boost. & MLE "
      r"& True & Boost. & MLE \\"]
bloco(L, r"$\eta_\mu$", MU, cens)
bloco(L, r"$\eta_\sigma$", SIG, cens)
bloco(L, r"$\log\lambda$", LAM, cens)
bloco(L, r"$\eta_\alpha$", AL, cens)
L += [r"\bottomrule", r"\end{tabular}", "}"]
open(os.path.join(OUT, "tabelas", "val_ipl_merged.tex"), "w").write("\n".join(L) + "\n")

print(f"wrote tabelas/val_pl.tex and tabelas/val_ipl_merged.tex ({ND} decimals) under {OUT}")
